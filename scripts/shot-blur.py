"""Writes src/lib/shotBlur.ts: a 12 px wide JPEG of the top of each case screenshot (as it is framed on the site),
used by next/image as a blurred placeholder while the real shot downloads. Run after replacing any public/cases/*.jpg:

    python3 scripts/shot-blur.py
"""
import base64, glob, io, os
from PIL import Image

out = {}
for f in sorted(glob.glob('public/cases/*.jpg')):
    im = Image.open(f).convert('RGB')
    w, h = im.size
    name = os.path.basename(f)
    if name.endswith('-m.jpg'):  # phone shots: framed tall, from the top
        crop = im.crop((0, 0, w, min(h, int(w * 2.0))))
    elif name.endswith('-top.jpg'):  # already the top of the page
        crop = im
    else:  # full-page shots: framed 16:10, object-top
        crop = im.crop((0, 0, w, min(h, int(w * 10 / 16))))
    tiny = crop.resize((12, max(1, round(12 * crop.height / crop.width))), Image.LANCZOS)
    buf = io.BytesIO()
    tiny.save(buf, 'JPEG', quality=50, optimize=True)
    out['/cases/' + name] = 'data:image/jpeg;base64,' + base64.b64encode(buf.getvalue()).decode()

lines = [
    '// generated by scripts/shot-blur.py from public/cases/*.jpg (12 px wide, the top of each shot as it is framed):',
    '// a blurred preview while a screenshot downloads, instead of an empty dark frame. Re-run after replacing a shot.',
    'export const shotBlur: Record<string, string> = {',
]
lines += [f"  '{k}': '{v}'," for k, v in out.items()]
lines.append('};')
with open('src/lib/shotBlur.ts', 'w') as fh:
    fh.write('\n'.join(lines) + '\n')
print(f'{len(out)} previews written')
